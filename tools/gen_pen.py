import math
from PIL import Image, ImageDraw

# 仿 Windows 经典铅笔（朝右下 45°）+ 笔身与笔头之间 2px 缝隙
#   中心轴：笔身 (7,7)→(23.293,23.293)，缝隙 2px，笔尖 (24.707,24.707)→(29,29)
#   1) 笔身（白斜矩形，末端缩短留缝） 2) 笔尖（白三角锥，起点后退留缝）
#   3) 铅芯（深灰） 4) 橡皮（稍暗白外凸）
# 4x supersampling -> LANCZOS 缩到 32x32
S, Z = 32, 4
img = Image.new('RGBA', (S * Z, S * Z), (0, 0, 0, 0))
d = ImageDraw.Draw(img)
P = lambda x, y: (x * Z, y * Z)

# 1) 笔身（半宽 2.2，末端缩到 23.293 留 2px 缝隙）
d.polygon([P(8.556, 5.444), P(24.849, 21.737), P(21.737, 24.849), P(5.444, 8.556)],
          fill=(255, 255, 255, 255))
# 2) 笔尖（白色三角锥，起点退到 24.707 留缝，尖端 29,29）
d.polygon([P(26.263, 23.151), P(29, 29), P(23.151, 26.263)], fill=(255, 255, 255, 255))
# 3) 铅芯（深灰小三角，从笔尖起点到尖端）
d.polygon([P(25.343, 24.071), P(29, 29), P(24.071, 25.343)], fill=(170, 170, 170, 255))
# 4) 橡皮（稍暗白，向左上外凸的帽子）
d.polygon([P(7.142, 4.556), P(8.556, 5.444), P(5.444, 8.556), P(4.556, 7.142)],
          fill=(220, 220, 220, 255))

img = img.resize((S, S), Image.LANCZOS)
img.save('assets/pen.png')
print('已生成 assets/pen.png（笔身与笔头间 2px 缝隙）', img.size)
